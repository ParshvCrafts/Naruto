// analyze.mjs — Zero-dependency geometric feature analysis for hand-sign disambiguation (S13).
//
//   node analyze.mjs [path-to-landmarks.json]   (default: landmarks_2026-04-18.json)
//
// Loads the landmark-collector export and prints, per sign, the distribution
// (min / max / mean / σ) of every feature the refinement gate uses PLUS candidate
// new features (inter-wrist distance, per-hand extension counts). It then prints a
// pairwise-overlap report so thresholds can be chosen at ≥2σ separation.
//
// Output is deterministic Markdown → pipe to report_v2.md.

import { readFileSync } from 'node:fs';

const path = process.argv[2] ?? 'landmarks_2026-04-18.json';
const data = JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));

// ── Landmark accessors ─────────────────────────────────────────────────────────
// A "hand" is { present, landmarks:[{index,name,x,y,z}] }. Index i lives at position i.
function lm(hand, i) {
  if (!hand || !hand.present || !hand.landmarks) return null;
  const p = hand.landmarks[i];
  return p && p.index === i ? p : hand.landmarks.find(q => q.index === i) ?? null;
}
const TIP = [8, 12, 16, 20];
const MCP = [5, 9, 13, 17];
const avg = a => a.reduce((s, v) => s + v, 0) / a.length;

// ── Feature extraction (one sample → named scalar features) ────────────────────
function features(sample) {
  const R = sample.right_hand, L = sample.left_hand;
  const f = {};
  const r8 = lm(R, 8), r5 = lm(R, 5), l8 = lm(L, 8);
  const l17 = lm(L, 17), l20 = lm(L, 20);
  const r0 = lm(R, 0), l0 = lm(L, 0);

  if (l8 && r8) {
    f.tiger_sym = Math.abs(l8.y - r8.y);   // |L8y - R8y| — small → Tiger
    f.ram_asym  = l8.y - r8.y;              // <0 → left higher → Ram
  }
  if (r8 && r5) f.r_index_ext = r5.y - r8.y;       // >0 → right index extended up
  if (l20 && l17) f.l_pinky_curl = l20.y - l17.y;  // >0 → left pinky curled (Dragon deep)
  if (r0 && l0) f.inter_wrist = Math.hypot(l0.x - r0.x, l0.y - r0.y); // hands joined → small

  // Per-hand extension count (tips above their MCP by >0.04)
  for (const [name, H] of [['r', R], ['l', L]]) {
    if (!H || !H.present) continue;
    let ext = 0;
    for (let k = 0; k < 4; k++) {
      const tip = lm(H, TIP[k]), mcp = lm(H, MCP[k]);
      if (tip && mcp && tip.y < mcp.y - 0.04) ext++;
    }
    f[`${name}_ext_count`] = ext;
  }
  // Serpent signature: avg fingertip y > avg MCP y on both hands (fingers point down)
  for (const [name, H] of [['r', R], ['l', L]]) {
    if (!H || !H.present) continue;
    const tips = TIP.map(i => lm(H, i)).filter(Boolean).map(p => p.y);
    const mcps = MCP.map(i => lm(H, i)).filter(Boolean).map(p => p.y);
    if (tips.length && mcps.length) f[`${name}_tip_minus_mcp`] = avg(tips) - avg(mcps);
  }
  return f;
}

// ── Stats helpers ──────────────────────────────────────────────────────────────
function stats(values) {
  const v = values.filter(x => Number.isFinite(x));
  if (!v.length) return null;
  const mean = avg(v);
  const sd = Math.sqrt(avg(v.map(x => (x - mean) ** 2)));
  return { n: v.length, min: Math.min(...v), max: Math.max(...v), mean, sd };
}
const fmt = x => (x === undefined || x === null) ? '—' : x.toFixed(4);

// ── Collect per-sign feature arrays ────────────────────────────────────────────
const signs = Object.keys(data.samples);
const perSign = {};          // sign → featureName → number[]
const featureNames = new Set();
for (const sign of signs) {
  perSign[sign] = {};
  for (const sample of data.samples[sign]) {
    const f = features(sample);
    for (const [k, val] of Object.entries(f)) {
      featureNames.add(k);
      (perSign[sign][k] ??= []).push(val);
    }
  }
}

// ── Report ─────────────────────────────────────────────────────────────────────
const out = [];
out.push(`# Refinement feature analysis — \`${path}\``);
out.push(`Generated by analyze.mjs. Samples per sign: ` +
  signs.map(s => `${s}=${data.samples[s].length}`).join(', ') + '\n');

for (const feat of [...featureNames].sort()) {
  out.push(`## ${feat}`);
  out.push('| sign | n | min | max | mean | σ |');
  out.push('|---|---|---|---|---|---|');
  for (const sign of signs) {
    const st = stats(perSign[sign][feat] ?? []);
    out.push(st ? `| ${sign} | ${st.n} | ${fmt(st.min)} | ${fmt(st.max)} | ${fmt(st.mean)} | ${fmt(st.sd)} |`
                : `| ${sign} | 0 | — | — | — | — |`);
  }
  // Pairwise separation: |Δmean| / (σa+σb). ≥2 ≈ clean 2σ separation.
  const sep = [];
  for (let i = 0; i < signs.length; i++) for (let j = i + 1; j < signs.length; j++) {
    const a = stats(perSign[signs[i]][feat] ?? []), b = stats(perSign[signs[j]][feat] ?? []);
    if (a && b) {
      const denom = (a.sd + b.sd) || 1e-9;
      sep.push(`${signs[i]}/${signs[j]}: ${(Math.abs(a.mean - b.mean) / denom).toFixed(2)}`);
    }
  }
  out.push(`\nseparation (|Δmean|/(σa+σb), ≥2 = clean): ${sep.join('  ·  ')}\n`);
}

console.log(out.join('\n'));
